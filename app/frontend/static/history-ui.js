  function language() {
    return window.PptAppSettings?.readLanguage?.() || localStorage.getItem("ppt-html-studio-language") || "zh";
  }

  function t(key) {
    const bundle = labels[language()] || labels.zh;
    return bundle[key] || labels.en[key] || key;
  }

  function escapeHtml(value) {
    return String(value || "").replace(/[&<>"']/g, (char) => ({
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#039;",
    }[char]));
  }

  function formatTime(value) {
    if (!value) return "";
    return new Intl.DateTimeFormat(language() === "zh" ? "zh-CN" : "en", {
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
    }).format(new Date(value));
  }

  function bytes(value) {
    const size = Number(value || 0);
    if (!size) return "0 MB";
    if (size > 1024 * 1024 * 1024) return `${(size / 1024 / 1024 / 1024).toFixed(2)} GB`;
    return `${(size / 1024 / 1024).toFixed(1)} MB`;
  }

  function ensureHistoryNav() {
    const nav = document.querySelector(".home-sidebar nav");
    if (!nav) return;
    state.syncingNav = true;
    let link = el("historyNav") || nav.querySelector("[data-history-nav='1']");
    if (!link) {
      link = document.createElement("a");
      link.id = "historyNav";
      link.dataset.historyNav = "1";
    }
    link.href = document.querySelector(".home-main") ? "#history" : "/#history";
    link.textContent = t("nav");
    link.removeAttribute("data-i18n");
    link.style.display = "";
    const home = [...nav.querySelectorAll("a")].find((node) => node.dataset.i18n === "home" || /\/$/.test(node.getAttribute("href") || ""));
    if (home && home.nextElementSibling !== link) {
      home.insertAdjacentElement("afterend", link);
    } else if (!home && link.parentElement !== nav) {
      nav.insertAdjacentElement("afterbegin", link);
    }
    if (state.active) link.classList.add("active");
    let importLink = el("htmlImportNav") || nav.querySelector("[data-html-import-nav='1']");
    if (!importLink) {
      importLink = document.createElement("a");
      importLink.id = "htmlImportNav";
      importLink.dataset.htmlImportNav = "1";
    }
    // Canonical editor entry; /html-import.html was never published.
    importLink.href = "/editor.html";
    importLink.textContent = t("html_import");
    importLink.removeAttribute("data-i18n");
    importLink.style.display = "";
    if (link.nextElementSibling !== importLink) link.insertAdjacentElement("afterend", importLink);
    state.syncingNav = false;
  }

  function observeSidebar() {
    if (state.observing) return;
    const nav = document.querySelector(".home-sidebar nav");
    if (!nav || !window.MutationObserver) return;
    state.observing = true;
    new MutationObserver(() => {
      if (state.syncingNav) return;
      requestAnimationFrame(() => {
        ensureHistoryNav();
        updateSidebarActive();
      });
    }).observe(nav, { childList: true, subtree: true, characterData: true });
  }

  function updateSidebarActive() {
    document.querySelectorAll(".home-sidebar nav a").forEach((node) => node.classList.remove("active"));
    if (state.active) {
      ensureHistoryNav();
      el("historyNav")?.classList.add("active");
    } else {
      document.querySelector(".home-sidebar nav a[data-i18n='home']")?.classList.add("active");
    }
  }

  function sourcePath(record, edit = false) {
    const map = {
      converter: "/converter.html",
      quick_create: "/ai-generate.html",
      chat_create: "/chat-create.html",
      poster: "/poster.html",
      html_import: "/editor.html",
    };
    const source = String(record?.source || "converter").toLowerCase().replace(/[\s-]+/g, "_");
    const params = new URLSearchParams({ history: record.id });
    if (edit) params.set("edit", "1");
    return `${map[source] || "/converter.html"}?${params.toString()}`;
  }

  function openRecord(record, edit = false) {
    sessionStorage.setItem("ppt-html-studio-open-history-id", record.id);
    sessionStorage.setItem("ppt-html-studio-open-history-edit", edit ? "1" : "0");
    window.location.assign(sourcePath(record, edit));
  }

  function slug(value) {
    return String(value || "ppt-html-history")
      .trim()
      .replace(/[\\/:*?"<>|]+/g, "-")
      .replace(/\s+/g, "-")
      .slice(0, 80) || "ppt-html-history";
  }

  function triggerBlobDownload(blob, filename) {
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = filename;
    link.rel = "noopener";
    document.body.appendChild(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }

  async function downloadRecord(record) {
    const fullRecord = await window.PptHistory.getRecord(record.id);
    const html = fullRecord?.editedHtml || fullRecord?.html || "";
    if (!html) {
      alert(t("missingHtml"));
      return;
    }
    const scrollHtml = fullRecord?.scrollHtml || html;
    if (window.JSZip) {
      const zip = new window.JSZip();
      zip.file("index.html", html);
      zip.file("index-scroll.html", scrollHtml);
      zip.file("index-single-file.html", html);
      zip.file("index-scroll-single-file.html", scrollHtml);
      zip.file("README-open.txt", "Open index.html for paged navigation, or index-scroll.html for continuous scrolling.\n");
      const blob = await zip.generateAsync({ type: "blob" });
      triggerBlobDownload(blob, `${slug(record.title)}.zip`);
      return;
    }
    triggerBlobDownload(new Blob([html], { type: "text/html;charset=utf-8" }), `${slug(record.title)}.html`);
  }

  function runThumbnailQueue() {
    while (state.thumbnailLoads < 1 && state.thumbnailQueue.length) {
      const task = state.thumbnailQueue.shift();
      if (!task.frame.isConnected || task.generation !== state.thumbnailGeneration) continue;
      state.thumbnailLoads += 1;
      window.PptHistory.getRecord(task.record.id)
        .then((fullRecord) => {
          if (task.frame.isConnected && task.generation === state.thumbnailGeneration) {
            const html = fullRecord?.editedHtml || fullRecord?.html || "";
            const cover = html && window.PptHistory.thumbnailFromHtml?.(html, fullRecord.title, fullRecord.source, fullRecord.style);
            if (!cover) return;
            task.frame.src = cover;
            task.frame.alt = fullRecord.title || "Presentation cover";
            task.frame.dataset.historyThumbReady = "1";
            window.PptHistory.updateRecord(fullRecord.id, { thumbnail: cover, thumbnailKind: "cover-v2" }).catch(() => {});
          }
        })
        .catch((error) => { task.frame.dataset.historyThumbError = error?.message || "cover-migration-failed"; })
        .finally(() => {
          state.thumbnailLoads -= 1;
          runThumbnailQueue();
        });
    }
  }

  function queueThumbnail(frame, record, generation) {
    if (!frame || !record || frame.dataset.historyThumbQueued === "1") return;
    frame.dataset.historyThumbQueued = "1";
    state.thumbnailQueue.push({ frame, record, generation });
    runThumbnailQueue();
  }

  function hydrateThumbnails(records) {
    state.thumbnailGeneration += 1;
    const generation = state.thumbnailGeneration;
    state.thumbnailQueue = [];
    state.thumbnailObserver?.disconnect();
    state.thumbnailObserver = null;
    const byId = new Map(records.map((record) => [record.id, record]));
    const frames = [...document.querySelectorAll("img[data-history-thumb]")];
    if (!("IntersectionObserver" in window)) {
      frames.forEach((frame) => queueThumbnail(frame, byId.get(frame.dataset.historyThumb), generation));
      return;
    }
    state.thumbnailObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        observer.unobserve(entry.target);
        const record = byId.get(entry.target.dataset.historyThumb);
        if (record && record.thumbnailKind !== "cover-v2") queueThumbnail(entry.target, record, generation);
      });
    }, { rootMargin: "320px 0px", threshold: 0.01 });
    frames.forEach((frame) => {
      const record = byId.get(frame.dataset.historyThumb);
      if (record?.thumbnailKind !== "cover-v2") state.thumbnailObserver.observe(frame);
    });
  }

